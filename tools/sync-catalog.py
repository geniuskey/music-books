#!/usr/bin/env python3
"""Generate the shelf from imported books and the future-volume roadmap."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
books = json.loads((ROOT / 'migration/books.json').read_text())['books']
# Books written here rather than imported. Keep these fields in sync with the book's own book.json.
LOCAL_BOOKS = [{
    'id': 'guitarbook', 'code': 'GTR', 'title': 'GuitarBook', 'subtitle': '기타 교과서',
    'headline': '줄 하나에서 나만의 연주까지',
    'description': '현의 물리와 튜닝, 지판과 TAB, 오픈·바레 코드와 CAGED, 스트로크와 코드 진행, 스케일과 리드 테크닉, 핑거스타일, 일렉 톤까지 — 브라우저의 가상 기타로 직접 튕기고 긁으며 배우는 기타 교과서.',
    'url': 'https://music.euiyun.com/guitar/', 'repo': 'https://github.com/geniuskey/music-books', 'field': 'music',
    'status': 'published', 'level': '입문', 'stage': 'instruments', 'slug': 'guitar', 'legacyUrl': None,
    'color': '#9a6237', 'colorDark': '#d9a066', 'motif': 'guitar',
    'topics': ['지판·TAB', '코드·CAGED', '스트로크', '스케일·솔로', '핑거스타일', '일렉 톤'],
}]
books = books + LOCAL_BOOKS
catalog = []
for book in books:
    entry = {k: book[k] for k in ('id','title','subtitle','headline','description','stage','status','color','colorDark','topics','motif','code','legacyUrl','slug')}
    entry['url'] = book['slug'] + '/'
    pages = list((ROOT / book['slug'] / 'chapters').glob('*.html'))
    entry['chapters'] = len(pages)
    entry['simulators'] = sum(p.read_text().count('class="sim"') for p in pages)
    catalog.append(entry)
catalog.extend(json.loads((ROOT / 'roadmap.json').read_text()))
(ROOT / 'catalog.js').write_text('/* Generated by tools/sync-catalog.py. Text: CC BY 4.0. */\nwindow.MUSIC_BOOKS = ' + json.dumps(catalog, ensure_ascii=False, indent=2) + ';\n')
print(f'Catalog: {len(books)} published, {len(catalog)-len(books)} planned')
